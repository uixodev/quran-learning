// Подготовка арабского текста к показу. Сохранённый текст не меняется.
//
// В тексте в стиле Tanzil «открытый» танвин записан знаками U+0657 (фатхатан),
// U+065E (даммтан), U+0656 (касратан). В шрифте Amiri Quran есть их стандартные
// аналоги U+08F0, U+08F1, U+08F2 (так же их заменяет Комплекс царя Фахда в своих
// шрифтах), а U+065E в нём нет вовсе. Начертание одно и то же.
const OPEN_TANWEEN = { 'ٗ': 'ࣰ', 'ٞ': 'ࣱ', 'ٖ': 'ࣲ' };

export const toDisplay = (s) => s.replace(/[ٖٗٞ]/g, (c) => OPEN_TANWEEN[c]);

const DIGITS = '٠١٢٣٤٥٦٧٨٩';
export const arabicNumber = (n) => String(n).replace(/\d/g, (d) => DIGITS[d]);

/** Знак конца аята с номером (U+06DD охватывает следующие цифры). */
export const ayahMarker = (n) => '۝' + arabicNumber(n);
